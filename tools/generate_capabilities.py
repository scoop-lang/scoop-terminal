#!/usr/bin/env python3
"""Generate the emulator query table and terminfo from the same supported profile."""

import argparse
import json
from pathlib import Path
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[1]


def terminfo_string(value):
    replacements = {"\x1b": "\\E", "\n": "\\n", "\r": "\\r", "\t": "\\t",
                    "\b": "\\b", "\x07": "^G", "\x7f": "^?", ",": "\\,",
                    "\\": "\\\\", " ": "\\s"}
    return "".join(replacements.get(char, char) for char in value)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--scoop", default=str(Path.home() / ".scoop/bin/scoop"))
    args = parser.parse_args()
    profile = json.loads((ROOT / "data/terminal-capabilities.json").read_text())
    entries = {"TN": profile["name"], "name": profile["name"]}
    lines = ["# Generated by tools/generate_capabilities.py; edit data/terminal-capabilities.json.",
             profile["name"] + "|Scoop terminal component,"]
    for name in profile["booleans"]:
        lines.append("\t" + name + ",")
        entries[name] = ""
    for name, value in profile["numbers"].items():
        lines.append(f"\t{name}#{value},")
        entries[name] = str(value)
    for name, value in profile["strings"].items():
        lines.append(f"\t{name}={terminfo_string(value)},")
        entries[name] = value
    for alias, name in profile["aliases"].items():
        entries[alias] = entries[name]
    source = ["package scoop.terminal.emulator", "",
              "// Generated from data/terminal-capabilities.json; do not edit.",
              "internal fun terminalCapability(name: String): String? = when (name) {"]
    for name, value in sorted(entries.items()):
        source.append(f"    case {json.dumps(name)} -> Some({json.dumps(value)})")
    source += ["    case _ -> None", "}", ""]
    with tempfile.TemporaryDirectory(prefix="scoop-terminal-capabilities-") as temp:
        path = Path(temp) / "capabilities.scoop"
        path.write_text("\n".join(source))
        subprocess.run([args.scoop, "fmt", str(path)], check=True, capture_output=True, text=True)
        outputs = {ROOT / "emulator/src/generated_capabilities.scoop": path.read_text(),
                   ROOT / "terminfo/scoop.terminfo": "\n".join(lines) + "\n"}
        for path, content in outputs.items():
            if args.check:
                if not path.exists() or path.read_text() != content:
                    raise SystemExit(f"out of date: {path.relative_to(ROOT)}")
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    print("capability table and terminfo are consistent")


if __name__ == "__main__":
    main()
